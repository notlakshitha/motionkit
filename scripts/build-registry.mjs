import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = process.cwd()
const catalog = JSON.parse(readFileSync(join(root, "content/catalog.json"), "utf8"))

const items = catalog.blocks.map((block) => {
  const item = {
    name: block.slug,
    type: "registry:block",
    title: block.title,
    description: block.description,
    files: block.files.map((file) => ({
      path: file,
      type: file.endsWith(".tsx") ? "registry:component" : "registry:lib",
      target: file.replace("registry/motionkit/", "components/motionkit/"),
    })),
  }

  if (block.dependencies.length > 0) {
    item.dependencies = block.dependencies
  }

  return item
})

const registry = {
  $schema: "https://ui.shadcn.com/schema/registry.json",
  name: catalog.name,
  homepage: catalog.homepage,
  items,
}

writeFileSync(join(root, "registry.json"), `${JSON.stringify(registry, null, 2)}\n`)

const sources = {}
const prompts = {}

for (const block of catalog.blocks) {
  sources[block.slug] = block.files.map((file) => ({
    filename: file.split("/").pop(),
    content: readFileSync(join(root, file), "utf8"),
  }))
  const promptPath = join(root, "content/prompts", `${block.slug}.md`)
  prompts[block.slug] = readFileSync(promptPath, "utf8")
}

mkdirSync(join(root, "lib/generated"), { recursive: true })

const generated = `/* Generated by scripts/build-registry.mjs. Do not edit by hand. */
export const blockSources: Record<string, { filename: string; content: string }[]> = ${JSON.stringify(sources, null, 2)}

export const blockPrompts: Record<string, string> = ${JSON.stringify(prompts, null, 2)}
`

writeFileSync(join(root, "lib/generated/block-sources.ts"), generated)
console.log(`Wrote registry.json and sources for ${catalog.blocks.length} blocks.`)
